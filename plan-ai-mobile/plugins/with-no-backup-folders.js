const fs = require("fs");
const path = require("path");
const {
  AndroidConfig,
  withAndroidManifest,
  withAppDelegate,
  withDangerousMod,
} = require("@expo/config-plugins");
const { mergeContents } = require("@expo/config-plugins/build/utils/generateCode");

// Meeting data must not leave the phone through a backup or a phone-to-phone
// transfer.
//
// iOS: recordings wait in Documents/recordings until the backend confirms the
// upload (src/services/recordingSessions.ts), and the auth cache lives in
// Documents/private (src/context/AuthContext.tsx). iOS backs up everything in
// Documents, and expo-file-system has no call to change that. So the app
// marks both folders at every launch: excluded from backup, which also covers
// the files inside, and readable only after the first unlock since boot. That
// class still lets a recording keep writing while the screen is locked. The
// folders stay in Documents on purpose: the OS never purges them, unlike the
// caches folder.
//
// Android: allowBackup is false in app.config.ts, but Android 12 and later
// ignore it for device-to-device transfer. data_extraction_rules.xml excludes
// every domain from both cloud backup and device transfer.

const IOS_FOLDERS = ["recordings", "private"];

const IOS_SNIPPET = `    if let documents = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask).first {
      for name in [${IOS_FOLDERS.map((f) => `"${f}"`).join(", ")}] {
        var folder = documents.appendingPathComponent(name, isDirectory: true)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? FileManager.default.setAttributes(
          [.protectionKey: FileProtectionType.completeUntilFirstUserAuthentication],
          ofItemAtPath: folder.path)
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        try? folder.setResourceValues(values)
      }
    }`;

const DOMAINS = [
  "root",
  "file",
  "database",
  "sharedpref",
  "external",
  "device_root",
  "device_file",
  "device_database",
  "device_sharedpref",
];
const excludeAll = DOMAINS.map((d) => `    <exclude domain="${d}" path="." />`).join("\n");
const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-no-backup-folders.js. Nothing is backed up or transferred. -->
<data-extraction-rules>
  <cloud-backup>
${excludeAll}
  </cloud-backup>
  <device-transfer>
${excludeAll}
  </device-transfer>
</data-extraction-rules>
`;

const withIosFolders = (config) =>
  withAppDelegate(config, (config) => {
    if (config.modResults.language !== "swift") {
      throw new Error(
        "with-no-backup-folders: expected a Swift AppDelegate, found " +
          config.modResults.language,
      );
    }
    // Fails the prebuild if the anchor is gone, so a template change cannot
    // silently ship meeting data back into iCloud.
    config.modResults.contents = mergeContents({
      src: config.modResults.contents,
      newSrc: IOS_SNIPPET,
      tag: "plan-ai-no-backup-folders",
      anchor: /return super\.application\(application, didFinishLaunchingWithOptions: launchOptions\)/,
      offset: 0,
      comment: "//",
    }).contents;
    return config;
  });

const withAndroidRulesFile = (config) =>
  withDangerousMod(config, [
    "android",
    async (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "data_extraction_rules.xml"), DATA_EXTRACTION_RULES);
      return config;
    },
  ]);

const withAndroidRulesAttribute = (config) =>
  withAndroidManifest(config, (config) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    app.$["android:dataExtractionRules"] = "@xml/data_extraction_rules";
    return config;
  });

module.exports = function withNoBackupFolders(config) {
  config = withIosFolders(config);
  config = withAndroidRulesFile(config);
  config = withAndroidRulesAttribute(config);
  return config;
};
